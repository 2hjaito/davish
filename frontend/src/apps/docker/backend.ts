// The Docker calls, or demo data in the plain browser preview.
import {
  type ContainerAction,
  dockerAct,
  dockerImage,
  dockerImages,
  dockerPlanImage,
  dockerPlanRun,
  dockerComposeCommand,
  dockerPlanStack,
  dockerCreateStack,
  dockerPullCommand,
  dockerRemoveImage,
  dockerPlanVolume,
  dockerRemoveVolume,
  dockerVolumes,
  dockerInspect,
  dockerList,
  dockerLogs,
  dockerPlan,
  dockerStats,
} from '../../lib/api/docker'
import { hasRuntime } from '../../lib/api/runtime'
import {
  mockAct,
  mockImage,
  mockImages,
  mockInspect,
  mockList,
  mockLogs,
  mockPlan,
  mockPlanImage,
  mockPlanRun,
  mockComposeCommand,
  mockPlanStack,
  mockCreateStack,
  mockPullCommand,
  mockRemoveImage,
  mockPlanVolume,
  mockRemoveVolume,
  mockVolumes,
  mockStats,
} from './mock'

export const backend = hasRuntime
  ? {
      list: dockerList,
      stats: dockerStats,
      inspect: dockerInspect,
      logs: dockerLogs,
      plan: dockerPlan,
      act: dockerAct,
      images: dockerImages,
      image: dockerImage,
      planImage: dockerPlanImage,
      removeImage: dockerRemoveImage,
      volumes: dockerVolumes,
      planVolume: dockerPlanVolume,
      removeVolume: dockerRemoveVolume,
      pullCommand: dockerPullCommand,
      planRun: dockerPlanRun,
      composeCommand: dockerComposeCommand,
      planStack: dockerPlanStack,
      createStack: dockerCreateStack,
    }
  : {
      list: (_serverID: string) => mockList(),
      stats: (_serverID: string) => mockStats(),
      inspect: (_serverID: string, name: string) => mockInspect(name),
      logs: (_serverID: string, name: string) => mockLogs(name),
      plan: mockPlan,
      act: (_serverID: string, name: string, action: ContainerAction) => mockAct(name, action),
      images: (_serverID: string) => mockImages(),
      image: (_serverID: string, ref: string) => mockImage(ref),
      planImage: mockPlanImage,
      removeImage: (_serverID: string, ref: string, _command: string) => mockRemoveImage(ref),
      volumes: (_serverID: string) => mockVolumes(),
      planVolume: mockPlanVolume,
      removeVolume: (_serverID: string, name: string, _command: string) => mockRemoveVolume(name),
      pullCommand: mockPullCommand,
      planRun: mockPlanRun,
      composeCommand: mockComposeCommand,
      planStack: mockPlanStack,
      createStack: mockCreateStack,
    }
