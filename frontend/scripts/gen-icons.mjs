const PACKS = {
  Dv: 'dv',
  Fi: 'fi',
  Lu: 'lu',
  Hi: 'hi',
  Bi: 'bi',
  Ri: 'ri',
  Md: 'md',
  Px: 'px',
  Si: 'si',
}

const root = dirname(dirname(fileURLToPath(import.meta.url)))
// The package's exports map does not expose package.json, so read it directly.
const pkgDir = join(root, 'node_modules/davi-icons')
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version

const sources = new Map()
function definition(component) {
  const prefix = component.slice(0, 2)
  const pack = PACKS[prefix]
  if (!pack) throw new Error(`unknown pack prefix for ${component}; add it to PACKS`)
  if (!sources.has(pack)) {
    sources.set(pack, readFileSync(join(pkgDir, 'dist/icons', `${pack}.js`), 'utf8'))
  }
  // Generated files look like: export const FiX = createDaviIcon({...json...});
  const marker = `export const ${component} = createDaviIcon(`
  const src = sources.get(pack)
  const start = src.indexOf(marker)
  if (start === -1) throw new Error(`${component} not found in davi-icons/${pack}`)
  const end = src.indexOf('\n});', start)
  const def = JSON.parse(src.slice(start + marker.length, end + 2))
  return { viewBox: def.viewBox, nodes: def.nodes }
}

const entries = Object.entries(ICONS)
  .map(([name, component]) => `  ${name}: ${JSON.stringify(definition(component))},`)
  .join('\n')

const out = `// GENERATED by scripts/gen-icons.mjs from davi-icons@${version}. Do not edit.
// Run \`npm run icons\` after changing the icon list in that script.

export type IconNode = [tag: string, attrs: Record<string, string | number | boolean>, children?: IconNode[]]

export interface IconDef {
  viewBox: string
  nodes: IconNode[]
}

export const icons = {
${entries}
} satisfies Record<string, IconDef>

export type IconName = keyof typeof icons
`
writeFileSync(join(root, 'src/lib/ui/icons.ts'), out)
console.log(`wrote ${entries.split('\n').length} icons`)
